// Cloudflare Pages Function replacement for api/social-card.js.
//
// The Vercel version renders the 1080x1350 card with a headless browser
// (@sparticuz/chromium + puppeteer-core) and returns a JPEG. That cannot
// run in Workers, and there is no free Workers-native rasteriser, so this
// version builds the same card as a pure SVG instead: same 1080x1350 size,
// same layout (full-bleed photo, navy gradient fade, logo top left,
// pink category, white headline, description), same colours
// (navy #01229a, pink #fe0862) and same Archivo typeface.
//
// URL, params and signature scheme are unchanged, so every og:image link
// already generated by social-card-url.js keeps working:
//   GET /api/social-card?image=&category=&headline=&description=&ts=&sig=
// The signature is HMAC-SHA256 (hex) over the canonical URLSearchParams
// string of image, category, headline, description, ts, keyed by
// REVIEW_PASSWORD, exactly as the Vercel endpoint verifies it. Verified
// with the Web Crypto API, which is native to Workers (no nodejs_compat
// needed, no dependency at all).
//
// Honest limitation: the response is image/svg+xml, not image/jpeg.
// Browsers render it fine, but Facebook / X scrapers do not accept SVG
// as og:image, so a generated card used as og:image will not show a
// preview image there. The article/album/concert pages fall back to the
// feature image or /assets/og-image.png when no usable card exists, and
// the review dashboard still previews the card. See the migration notes.

const WIDTH = 1080;
const HEIGHT = 1350;
const MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;
const CACHE_CONTROL = 'public, max-age=3600, s-maxage=86400, stale-while-revalidate=604800';
const NAVY = '#01229a';
const PINK = '#fe0862';

function json(status, data) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { 'Content-Type': 'application/json' },
  });
}

function esc(value = '') {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function validPublicHttps(value) {
  try {
    const u = new URL(value);
    if (u.protocol !== 'https:') return false;
    const h = u.hostname.toLowerCase();
    if (h === 'localhost' || h.endsWith('.local') || h === '127.0.0.1' || h === '0.0.0.0' || h === '::1') return false;
    if (/^10\./.test(h) || /^192\.168\./.test(h) || /^172\.(1[6-9]|2\d|3[01])\./.test(h)) return false;
    return true;
  } catch {
    return false;
  }
}

async function hmacHex(secret, data) {
  const key = await crypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(secret),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign'],
  );
  const sig = await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(data));
  return [...new Uint8Array(sig)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

// Constant-time string comparison, mirroring crypto.timingSafeEqual.
function timingSafeEqual(a, b) {
  const aa = String(a || '');
  const bb = String(b || '');
  if (aa.length !== bb.length) return false;
  let diff = 0;
  for (let i = 0; i < aa.length; i++) diff |= aa.charCodeAt(i) ^ bb.charCodeAt(i);
  return diff === 0;
}

function headlineSize(len) {
  if (len > 110) return 56;
  if (len > 82) return 64;
  if (len > 58) return 74;
  return 82;
}

function descriptionSize(len) {
  if (len > 190) return 24;
  if (len > 135) return 26;
  return 29;
}

// Approximate glyph width as a fraction of font size, for Archivo ExtraBold.
// Workers has no font metrics, so wrapping is estimated; the 1.06 safety
// factor keeps lines inside the card even when the estimate runs narrow.
function charWidth(ch) {
  if (ch === ' ') return 0.3;
  if ('iljft.,:;\'!|()[]'.includes(ch)) return 0.32;
  if ('mwMW'.includes(ch)) return 0.88;
  if (ch >= 'A' && ch <= 'Z') return 0.7;
  if (ch >= '0' && ch <= '9') return 0.58;
  if ('@#$%&'.includes(ch)) return 0.72;
  if (ch === '-') return 0.36;
  return 0.56;
}

function textWidth(text, fontSize) {
  let w = 0;
  for (const ch of String(text)) w += charWidth(ch);
  return w * fontSize * 1.06;
}

function wrapText(text, maxWidth, fontSize, maxLines) {
  const words = String(text).split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words) {
    const next = line ? line + ' ' + word : word;
    if (textWidth(next, fontSize) <= maxWidth || !line) {
      line = next;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  if (lines.length <= maxLines) return lines;
  const kept = lines.slice(0, maxLines);
  let last = kept[maxLines - 1];
  while (last && textWidth(last + '...', fontSize) > maxWidth) {
    const cut = last.lastIndexOf(' ');
    last = cut > 0 ? last.slice(0, cut) : last.slice(0, -1);
  }
  kept[maxLines - 1] = (last || '') + '...';
  return kept;
}

function svg({ image, category, headline, description, logoUrl }) {
  const hs = headlineSize(headline.length);
  const ds = descriptionSize(description.length);
  const headlineLines = wrapText(headline, 940, hs, 5);
  const descriptionLines = description ? wrapText(description, 880, ds, 4) : [];

  // Bottom-anchored block, mirroring the original CSS: content sits
  // 74px above the bottom, category 24px with a 20px gap, headline
  // line-height 0.91, 22px gap, description line-height 1.22.
  const contentBottom = HEIGHT - 74;
  const catH = 24;
  const gap1 = 20;
  const gap2 = 22;
  const headlineBlock = 0.78 * hs + (headlineLines.length - 1) * 0.91 * hs + 0.22 * hs;
  const descBlock = descriptionLines.length
    ? 0.78 * ds + (descriptionLines.length - 1) * 1.22 * ds + 0.22 * ds
    : 0;
  const total = catH + gap1 + headlineBlock + (descriptionLines.length ? gap2 + descBlock : 0);
  const top = contentBottom - total;

  const catBaseline = top + 0.78 * catH;
  const headlineFirst = top + catH + gap1 + 0.78 * hs;
  const headlineBaselines = headlineLines.map((_, i) => headlineFirst + i * 0.91 * hs);
  const descFirst = descriptionLines.length
    ? headlineBaselines[headlineBaselines.length - 1] + 0.22 * hs + gap2 + 0.78 * ds
    : 0;
  const descBaselines = descriptionLines.map((_, i) => descFirst + i * 1.22 * ds);

  const headlineText = headlineLines
    .map((line, i) => `    <text x="70" y="${headlineBaselines[i].toFixed(1)}" font-size="${hs}" letter-spacing="-0.035em" fill="white">${esc(line)}</text>`)
    .join('\n');
  const descriptionText = descriptionLines
    .map((line, i) => `    <text class="desc" x="70" y="${descBaselines[i].toFixed(1)}" font-size="${ds}" letter-spacing="-0.01em" fill="rgba(255,255,255,0.92)">${esc(line)}</text>`)
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>\n` +
`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}" role="img" aria-label="${esc(headline)}">
  <title>${esc(headline)}</title>
  <style>
    @import url('https://fonts.googleapis.com/css2?family=Archivo:wght@500;800&amp;display=swap');
    text{font-family:'Archivo',Arial,Helvetica,sans-serif;font-weight:800}
    .desc{font-weight:500}
  </style>
  <defs>
    <linearGradient id="fade" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="${NAVY}" stop-opacity="0"/>
      <stop offset="34%" stop-color="${NAVY}" stop-opacity="0"/>
      <stop offset="46%" stop-color="${NAVY}" stop-opacity="0.10"/>
      <stop offset="58%" stop-color="${NAVY}" stop-opacity="0.36"/>
      <stop offset="72%" stop-color="${NAVY}" stop-opacity="0.72"/>
      <stop offset="89%" stop-color="${NAVY}" stop-opacity="0.94"/>
      <stop offset="100%" stop-color="${NAVY}" stop-opacity="1"/>
    </linearGradient>
    <filter id="txt-shadow" x="-10%" y="-10%" width="120%" height="120%">
      <feDropShadow dx="0" dy="2" stdDeviation="6" flood-color="#000000" flood-opacity="0.28"/>
    </filter>
    <filter id="logo-glow" x="-10%" y="-10%" width="120%" height="120%">
      <feDropShadow dx="0" dy="0" stdDeviation="2" flood-color="#ffffff" flood-opacity="0.98"/>
      <feDropShadow dx="0" dy="2" stdDeviation="7" flood-color="#000000" flood-opacity="0.18"/>
    </filter>
  </defs>
  <rect width="${WIDTH}" height="${HEIGHT}" fill="${NAVY}"/>
  <image href="${esc(image)}" xlink:href="${esc(image)}" x="0" y="0" width="${WIDTH}" height="${HEIGHT}" preserveAspectRatio="xMidYMid slice"/>
  <rect width="${WIDTH}" height="${HEIGHT}" fill="url(#fade)"/>
  <image href="${esc(logoUrl)}" xlink:href="${esc(logoUrl)}" x="58" y="54" width="260" height="44" preserveAspectRatio="xMidYMid meet" filter="url(#logo-glow)"/>
  <g filter="url(#txt-shadow)">
    <text x="70" y="${catBaseline.toFixed(1)}" font-size="24" letter-spacing="0.12em" fill="${PINK}">${esc(category)}</text>
${headlineText}
${descriptionText}
  </g>
</svg>`;
}

export async function onRequest(context) {
  const { request, env } = context;
  if (request.method !== 'GET') return json(405, { error: 'Method not allowed' });

  const secret = env.REVIEW_PASSWORD || '';
  if (!secret) return json(503, { error: 'Renderer is not configured' });

  const url = new URL(request.url);
  const raw = new URLSearchParams();
  for (const key of ['image', 'category', 'headline', 'description', 'ts']) {
    raw.set(key, url.searchParams.get(key) || '');
  }
  const sig = url.searchParams.get('sig') || '';
  const expected = await hmacHex(secret, raw.toString());
  if (!sig || !timingSafeEqual(sig, expected)) return json(403, { error: 'Invalid image signature' });

  const ts = Number(raw.get('ts'));
  if (!Number.isFinite(ts) || Math.abs(Date.now() - ts) > MAX_AGE_MS) {
    return json(403, { error: 'Image URL expired' });
  }

  const image = raw.get('image');
  const category = (raw.get('category') || 'K-POP').slice(0, 60);
  const headline = raw.get('headline').slice(0, 180);
  const description = raw.get('description').slice(0, 260);
  if (!image || !headline || !validPublicHttps(image)) {
    return json(400, { error: 'Valid HTTPS image and headline are required' });
  }

  const logoUrl = url.origin + '/assets/hallyuscope-logo.png';

  return new Response(svg({ image, category, headline, description, logoUrl }), {
    status: 200,
    headers: {
      'Content-Type': 'image/svg+xml; charset=utf-8',
      'Cache-Control': CACHE_CONTROL,
    },
  });
}
